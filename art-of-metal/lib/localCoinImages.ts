// Placeholder colors by metal type
export function metalPlaceholderColor(metal: string): string {
  const m = metal.toLowerCase();
  if (m.includes("gold")) return "#1A1408";
  if (m.includes("silver")) return "#0E0E14";
  if (m.includes("copper") || m.includes("bronze") || m.includes("brass")) return "#120A04";
  return "#0E0E0E";
}

